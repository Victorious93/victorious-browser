/**
 * Certs screen: export the local inspection CA, show its SHA-256 fingerprint,
 * launch the guided (manual) OS install flow, and optionally regenerate the root.
 */
@Composable
fun CertScreen(
    onBack: () -> Unit,
    modifier: Modifier = Modifier,
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()

    var fingerprint by remember { mutableStateOf("…") }
    var regenerated by remember { mutableStateOf(LocalCaProvider.hasRegenerated(context)) }
    var status by remember { mutableStateOf<String?>(null) }
    var confirmRegen by remember { mutableStateOf(false) }
    var busy by remember { mutableStateOf(false) }

    fun refreshFingerprint() {
        scope.launch {
            fingerprint = withContext(Dispatchers.IO) {
                runCatching { CaExportManager.fingerprint(context) }.getOrDefault("(unavailable)")
            }
        }
    }
    remember { refreshFingerprint(); true }

    Column(
        modifier = modifier
            .fillMaxSize()
            .padding(12.dp)
            .verticalScroll(rememberScrollState()),
    ) {
        NeonToolHeader(title = "Inspection CA", onBack = onBack)
        Text(
            "Export and (manually) install the local inspection root used by the " +
                "intercepting proxy. This browser already trusts it for its OWN WebView " +
                "via network_security_config. Other apps will NOT trust a user-installed " +
                "CA on modern Android — installing it is an OS step only you can complete.",
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        Spacer(Modifier.height(8.dp))

        Card(colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant)) {
            Column(Modifier.padding(12.dp)) {
                Text("CA SHA-256 fingerprint", style = MaterialTheme.typography.titleSmall, color = NeonCyan)
                Text(
                    fingerprint,
                    modifier = Modifier
                        .fillMaxWidth()
                        .horizontalScroll(rememberScrollState()),
                    style = MaterialTheme.typography.bodySmall,
                    fontFamily = FontFamily.Monospace,
                )
                if (regenerated) {
                    Spacer(Modifier.height(4.dp))
                    Text(
                        "Using REGENERATED root (filesDir). The baked-in root is overridden.",
                        style = MaterialTheme.typography.labelSmall,
                        color = NeonMagenta,
                    )
                }
            }
        }

        Spacer(Modifier.height(8.dp))
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            Button(
                enabled = !busy,
                onClick = {
                    busy = true
                    status = "Exporting…"
                    scope.launch {
                        val res = withContext(Dispatchers.IO) {
                            runCatching { CaExportManager.exportBoth(context) }
                        }
                        busy = false
                        status = res.fold(
                            onSuccess = { "Exported PEM → ${it.pemLocation ?: "failed"}; CRT → ${it.derLocation ?: "failed"}" },
                            onFailure = { "Export failed: ${it.message}" },
                        )
                    }
                },
            ) { Text("Export CA") }
            OutlinedButton(onClick = {
                val intent = CaInstallHelper.installIntent(context)
                val ok = intent != null && runCatching { context.startActivity(intent); true }.getOrDefault(false)
                if (!ok) {
                    runCatching { context.startActivity(CaInstallHelper.securitySettingsIntent()) }
                    status = "Opened Security settings — install the exported CA manually."
                } else {
                    status = "Opened OS certificate installer — confirm the install."
                }
            }) { Text("Install CA") }
            OutlinedButton(onClick = {
                runCatching { context.startActivity(CaInstallHelper.securitySettingsIntent()) }
            }) { Text("Security settings") }
        }

        Spacer(Modifier.height(12.dp))
        Text("Guided install steps", style = MaterialTheme.typography.titleSmall, color = NeonCyan)
        CaInstallHelper.steps.forEach { step ->
            Text("• $step", style = MaterialTheme.typography.bodySmall)
        }

        Spacer(Modifier.height(12.dp))
        Card(colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)) {
            Column(Modifier.padding(12.dp)) {
                Text("Regenerate root", style = MaterialTheme.typography.titleSmall, color = NeonMagenta)
                Text(
                    "Generates a brand-new local root. WARNING: this INVALIDATES any CA " +
                        "you previously exported or installed, and takes effect on the next " +
                        "proxy start. You will need to re-export and re-install.",
                    style = MaterialTheme.typography.labelSmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
                Spacer(Modifier.height(6.dp))
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    OutlinedButton(enabled = !busy, onClick = { confirmRegen = true }) {
                        Text("Regenerate…")
                    }
                    if (regenerated) {
                        OutlinedButton(enabled = !busy, onClick = {
                            LocalCaProvider.revertToBaked(context)
                            regenerated = false
                            status = "Reverted to baked-in root."
                            refreshFingerprint()
                        }) { Text("Revert to baked") }
                    }
                }
            }
        }

        status?.let {
            Spacer(Modifier.height(8.dp))
            Text(it, style = MaterialTheme.typography.bodySmall, color = NeonMagenta)
        }
        Spacer(Modifier.height(12.dp))
    }

    if (confirmRegen) {
        AlertDialog(
            onDismissRequest = { confirmRegen = false },
            title = { Text("Regenerate inspection root?") },
            text = {
                Text(
                    "This creates a new root key + cert. Any previously exported or " +
                        "installed CA will stop working and must be re-exported/installed. " +
                        "Continue?",
                )
            },
            confirmButton = {
                TextButton(onClick = {
                    confirmRegen = false
                    busy = true
                    status = "Regenerating…"
                    scope.launch {
                        val res = withContext(Dispatchers.IO) {
                            runCatching { LocalCaProvider.persistRegenerated(context) }
                        }
                        busy = false
                        regenerated = LocalCaProvider.hasRegenerated(context)
                        status = res.fold(
                            onSuccess = { "Regenerated. Re-export + re-install the new CA." },
                            onFailure = { "Regenerate failed: ${it.message}" },
                        )
                        refreshFingerprint()
                    }
                }) { Text("Regenerate", color = NeonMagenta) }
            },
            dismissButton = {
                TextButton(onClick = { confirmRegen = false }) { Text("Cancel") }
            },
        )
    }
}
